"""Generates rust/zeit-core/src/radtran_tables.rs from FORCE 3.11.00's table-ll.c.

FORCE (Framework for Operational Radiometric Correction for Environmental monitoring), Copyright (C) 2013-2022
David Frantz, GPL-3.0-or-later. The tables it reads are the exoatmospheric irradiance (Thuillier spectrum, 1 nm,
410-2400 nm), the water vapour absorption (HITRAN 2016), the ozone absorption (Bird & Riordan 1986), the wavelengths
and the relative spectral response (RSR) of every band of Landsat 4, 5, 7, 8 and Sentinel-2A and B (courtesy of
USGS/ESA); the water aerosol library `_AERO_WATERLIB_` (26 spectra, 410-900 nm) is read by `water_lib` of aod-ll.c and is
generated too; `_AERO_LANDLIB_` (34 x 1991) is skipped: `land_lib` never reads it (it returns one spectrum of zeros)
and the shadow targets that would use it are disabled in FORCE 3.11.00.

C parses `0.41` as a double and converts it to float; numpy does the same here (float64, then float32), and the
shortest decimal that round-trips the float32 is written, so Rust reads back exactly the float of the C table.

The RSR is stored per band as the span between its first and last non-zero value (`start`, `values`): the zeros
around it add nothing to the sums that FORCE takes over the full 1991 wavelengths.

    wsl -e bash -lc 'python3 /mnt/c/.../tools/gen_radtran_tables.py ~/force-src/src/modules/lower-level/table-ll.c \
        /mnt/c/.../rust/zeit-core/src/radtran_tables.rs'
"""
import re
import sys

import numpy as np

N = 1991


def block(text, name, dims):
    m = re.search(r"const\s+float\s+" + re.escape(name) + r"\s*" + dims + r"\s*=\s*\{(.*?)\};", text, re.S)
    return m.group(1)


def numbers(s):
    return [np.float32(float(t)) for t in re.findall(r"[-+]?\d*\.?\d+(?:[eE][-+]?\d+)?", s)]


def fmt(v):
    s = str(np.float32(v))
    return s if ("." in s or "e" in s) else s + ".0"


def emit_array(out, name, vals, indent=""):
    out.append(f"{indent}pub static {name}: [f32; {len(vals)}] = [")
    line = indent + "   "
    for v in vals:
        tok = " " + fmt(v) + ","
        if len(line) + len(tok) > 118:
            out.append(line)
            line = indent + "   "
        line += tok
    out.append(line)
    out.append(f"{indent}];")


def main(src, dst):
    text = open(src, encoding="latin-1").read()
    tables = {}
    for name in ("_E0_", "_AW_", "_AO_", "_WVL_"):
        v = numbers(block(text, name, r"\[1991\]"))
        assert len(v) == N, (name, len(v))
        tables[name] = v
    wl = numbers(block(text, "_AERO_WATERLIB_", r"\[26\]\[491\]"))
    assert len(wl) == 26 * 491, len(wl)
    rsr_text = block(text, "_RSR_", r"\[56\]\[1991\]")
    rows = [numbers(r) for r in re.findall(r"\{([^{}]*)\}", rsr_text)]
    assert len(rows) == 56 and all(len(r) == N for r in rows), (len(rows), [len(r) for r in rows])
    starts = dict(re.findall(r"const int _RSR_START_(\w+)_ = (\d+);", text))

    out = [
        "//! The tables of FORCE's radiative transfer: GENERATED by tools/gen_radtran_tables.py from FORCE 3.11.00",
        "//! src/modules/lower-level/table-ll.c; do not edit by hand.",
        "//!",
        "//! Copyright (C) 2013-2022 David Frantz, FORCE, GPL-3.0-or-later (https://github.com/davidfrantz/force).",
        "//! `E0`: exoatmospheric irradiance, Thuillier spectrum, W/m2/um; `AW`: water vapour absorption, HITRAN 2016,",
        "//! 1/cm; `AO`: ozone absorption, Bird & Riordan 1986; `WVL`: the wavelengths in um (410-2400 nm in steps of",
        "//! 1 nm, 1991 values); `RSR`: the relative spectral response of each band on that grid, courtesy of USGS/ESA,",
        "//! as `(start, values)`, the span from the first to the last non-zero value (the rest is zero).",
        "//!",
        "//! RSR rows: Landsat 4 TM 0-6, Landsat 5 TM 7-13, Landsat 7 ETM+ 14-20 (blue, green, red, nir, swir1, swir2,",
        "//! thermal); Landsat 8 OLI 21-29 (aerosol, blue, green, red, nir, cirrus, swir1, swir2, thermal);",
        "//! Sentinel-2A MSI 30-42 and 2B 43-55 (aerosol, blue, green, red, rededge1, rededge2, niredge, lai, nir, wvp,",
        "//! cirrus, swir1, swir2). FORCE points Landsat 9 at the Landsat 8 rows and Sentinel-2C and 2D at the 2A rows.",
        "",
        "pub const WVL_DIM: usize = 1991;",
        "pub const RSR_DIM: usize = 56;",
        "",
    ]
    for k in ("LND04", "LND05", "LND07", "LND08", "LND09", "SEN2A", "SEN2B", "SEN2C", "SEN2D"):
        out.append(f"pub const RSR_START_{k}: usize = {starts[k]};")
    out.append("")
    for name, vals in tables.items():
        out.append("#[rustfmt::skip]")
        emit_array(out, name[1:-1], vals)
        out.append("")
    out.append("/// Water aerosol library (`_AERO_WATERLIB_`): 26 reflectance spectra of water bodies on the first 491")
    out.append("/// wavelengths (410-900 nm), row-major: spectrum `i` is `AERO_WATERLIB[i * 491..(i + 1) * 491]`.")
    out.append("pub const AERO_WATERLIB_N: usize = 26;")
    out.append("pub const AERO_WATERLIB_W: usize = 491;")
    out.append("#[rustfmt::skip]")
    emit_array(out, "AERO_WATERLIB", wl)
    out.append("")
    out.append("#[rustfmt::skip]")
    out.append("pub static RSR: [(usize, &[f32]); RSR_DIM] = [")
    for i, r in enumerate(rows):
        nz = [j for j, v in enumerate(r) if v != 0]
        if not nz:
            out.append(f"    (0, &[]), // {i}: all zero in 410-2400 nm")
            continue
        lo, hi = nz[0], nz[-1] + 1
        out.append(f"    ({lo}, &[ // {i}")
        line = "       "
        for v in r[lo:hi]:
            tok = " " + fmt(v) + ","
            if len(line) + len(tok) > 118:
                out.append(line)
                line = "       "
            line += tok
        out.append(line)
        out.append("    ]),")
    out.append("];")
    open(dst, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
    print(f"wrote {dst}: {sum(1 for r in rows if any(v != 0 for v in r))} non-empty RSR rows")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
