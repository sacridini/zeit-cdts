#!/bin/bash
# Builds resmerge_harness.c from FORCE 3.11.00's own source (resmerge-ll.c: resolution_merge_1, _2 and _3, starfm,
# starfm_candidate_t, rescale_weight_resmerge, improphe_resmerge; imagefuns-cl.c: distance_kernel and gauss_kernel;
# copied verbatim) behind shims.h, and compiles it against the real GSL 2.7 of the conda env `force-ref`.
#
#   wsl -e bash -lc 'bash /mnt/c/.../benchmarks/vs_originals/force_resmerge/make_harness.sh [FORCE_SRC] [OUT_DIR]'
#
# TRAP: conda-forge's libgslcblas.so and libgslcblas.so.0 are symlinks to OpenBLAS (libcblas.so.3), whose dnrm2 and
# dgemv round differently from GSL's reference CBLAS (the scaled sum of squares of GSL's source), which Zeit ports.
# The harness is therefore linked statically to libgsl.a and libgslcblas.a: no shared CBLAS to resolve to.
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
SRC=${1:-$HOME/force-src/src/modules}
OUT=${2:-$HOME/force-ref-work/resmerge}
source ~/force-ref-work/env.sh
GSLCBLAS_A=$CONDA_PREFIX/lib/libgslcblas.a
[ -f "$GSLCBLAS_A" ] && [ -f "$CONDA_PREFIX/lib/libgsl.a" ] || { echo "no static GSL in $CONDA_PREFIX/lib"; exit 1; }
mkdir -p "$OUT"
C=$OUT/resmerge_harness.c
{
  echo "/* GENERATED by make_harness.sh: FORCE 3.11.00's resmerge-ll.c (resolution_merge_1, _2 and _3, starfm,"
  echo " * improphe_resmerge, rescale_weight_resmerge) and imagefuns-cl.c (distance_kernel, gauss_kernel), verbatim,"
  echo " * Copyright (C) 2013-2022 David Frantz, GPL-3.0-or-later, behind shims.h. The STARFM part is adopted from the"
  echo " * USDA-ARS version, STARFM Copyright (C) 2005-2014 Feng Gao (resmerge-ll.c lines 23-38, quoted in src/starfm.rs). */"
  cat "$HERE/shims.h"
  echo '#include <gsl/gsl_multifit.h>'
  echo
  sed -n 60,123p "$SRC/cross-level/imagefuns-cl.c"
  echo
  sed -n 52,62p "$SRC/lower-level/resmerge-ll.c"
  echo
  sed -n 73,507p "$SRC/lower-level/resmerge-ll.c"
  echo
  sed -n 510,945p "$SRC/lower-level/resmerge-ll.c"
  cat "$HERE/main.inc"
} > "$C"
# forward declarations that FORCE's header has
sed -i 's|^#include <gsl/gsl_multifit.h>|#include <gsl/gsl_multifit.h>\ndouble rescale_weight_resmerge(double weight, double minweight, double maxweight);\nshort **improphe_resmerge(int nx, int ny, brick_t *QAI, short **toa_, float **KDIST, int h, int nb_m, int nb_c, int *bands_m, int *bands_c, int nk, int mink);\nint distance_kernel(int nk, float ***kernel);\nint gauss_kernel(int nk, float sigma, float ***kernel);\nfloat *starfm(int nx, int ny, brick_t *QAI, float **coarse, float **fine, int r);|' "$C"
gcc -O2 -std=gnu11 -fopenmp -I"$CONDA_PREFIX/include" -o "$OUT/resmerge_harness" "$C" \
  -L"$CONDA_PREFIX/lib" -l:libgsl.a "$GSLCBLAS_A" -lm
echo "built $OUT/resmerge_harness (GSL $(gsl-config --version))"
ldd "$OUT/resmerge_harness" | grep -i 'gsl\|blas' || echo "no shared GSL or BLAS in the executable (static)"
