#!/bin/bash
# Builds starfm_harness.c from FORCE 3.11.00's own starfm() (resmerge-ll.c: starfm_candidate_t and starfm, the
# struct and the function up to its `return`, copied verbatim) behind shims.h, to compare zeit.starfm with FORCE's general path (any radius).
#
#   wsl -e bash -lc 'bash /mnt/c/.../benchmarks/vs_originals/force_resmerge/make_starfm_harness.sh [FORCE_SRC] [OUT_DIR]'
#
# FORCE's starfm() hard-codes, for `resolution_merge_3`, what a general STARFM would take as arguments: two pairs
# (`npair = 2`, `slice_value[2]`), `nclass = 40` and every uncertainty 0.002 (only the radius `r` is an argument).
# Exactly those five tokens are replaced by globals (set from the command line, FORCE's values by default) with sed;
# with the defaults the function is FORCE's to the letter. Everything else, the arithmetic included, is verbatim.
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
SRC=${1:-$HOME/force-src/src/modules}
OUT=${2:-$HOME/force-ref-work/starfm}
mkdir -p "$OUT"
C=$OUT/starfm_harness.c
F=$SRC/lower-level/resmerge-ll.c
{
  echo "/* GENERATED by make_starfm_harness.sh: FORCE 3.11.00's resmerge-ll.c (starfm_candidate_t, starfm), verbatim but for"
  echo " * the five hard-coded constants replaced by globals (see make_starfm_harness.sh), Copyright (C) 2013-2022"
  echo " * David Frantz, GPL-3.0-or-later, behind shims.h. The STARFM part is adopted from the USDA-ARS version, STARFM"
  echo " * Copyright (C) 2005-2014 Feng Gao (resmerge-ll.c lines 23-38, quoted in src/starfm.rs). */"
  cat "$HERE/shims.h"
  echo 'static int g_npair = 2; static float g_nclass = 40, g_unc_coarse = 0.002, g_unc_fine = 0.002;'
  sed -n '/^\/\*\* StarFM candidate struct/,/} starfm_candidate_t;/p' "$F"
  echo
  sed -n 698,945p "$F" \
    | sed -e 's|int pair, npair = 2;|int pair, npair = g_npair;|' \
          -e 's|float slice_value\[2\], std, nclass = 40;|float slice_value[16], std, nclass = g_nclass;|' \
          -e 's|unc_coarse_1 = unc_coarse_2 = unc_fine  = 0.002;|unc_coarse_1 = unc_coarse_2 = g_unc_coarse; unc_fine = g_unc_fine;|'
  cat "$HERE/starfm_main.inc"
} > "$C"
grep -q 'g_npair;' "$C" && grep -q 'slice_value\[16\]' "$C" && grep -q 'g_unc_fine;' "$C" || { echo "sed did not match"; exit 1; }
gcc -O2 -std=gnu11 -fopenmp -o "$OUT/starfm_harness" "$C" -lm
echo "built $OUT/starfm_harness"
