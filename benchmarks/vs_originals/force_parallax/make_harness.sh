#!/bin/bash
# Builds parallax_harness.c from FORCE 3.11.00's own source (cloud-ll.c: cloud_parallax; imagefuns-cl.c: gauss_kernel and
# buffer_; stats-cl.c: covar_recurrence and variance; queue-cl.c: the FIFO; copied verbatim, with ONE line added to
# cloud_parallax that hands a copy of the CDI to the harness) behind shims.h, and compiles it with gcc -O2.
#
#   wsl -e bash -lc 'bash /mnt/c/.../benchmarks/vs_originals/force_parallax/make_harness.sh [FORCE_SRC] [OUT_DIR]'
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
SRC=${1:-$HOME/force-src/src/modules}
OUT=${2:-$HOME/force-ref-work/parallax}
mkdir -p "$OUT"
C=$OUT/parallax_harness.c
# a function from its first line to its closing brace in column 0
fn() { awk -v s="$2" 'NR>=s{print} NR>=s && /^}/{exit}' "$1"; }
line() { grep -n "$2" "$1" | head -1 | cut -d: -f1; }
{
  echo "/* GENERATED by make_harness.sh: FORCE 3.11.00's cloud_parallax (cloud-ll.c), gauss_kernel and buffer_"
  echo " * (imagefuns-cl.c), covar_recurrence and variance (stats-cl.c) and the queue (queue-cl.c), verbatim, Copyright (C)"
  echo " * 2013-2022 David Frantz, GPL-3.0-or-later, behind shims.h; the one added line hands the CDI to the harness. */"
  cat "$HERE/shims.h"
  echo
  for name in create_queue destroy_queue enqueue dequeue; do
    fn "$SRC/cross-level/queue-cl.c" "$(grep -n "^[a-z]* *$name(" "$SRC/cross-level/queue-cl.c" | head -1 | cut -d: -f1)"
  done
  fn "$SRC/cross-level/stats-cl.c" "$(line "$SRC/cross-level/stats-cl.c" '^void covar_recurrence')"
  fn "$SRC/cross-level/stats-cl.c" "$(line "$SRC/cross-level/stats-cl.c" '^double variance')"
  fn "$SRC/cross-level/imagefuns-cl.c" "$(line "$SRC/cross-level/imagefuns-cl.c" '^int gauss_kernel')"
  fn "$SRC/cross-level/imagefuns-cl.c" "$(line "$SRC/cross-level/imagefuns-cl.c" '^int buffer_')"
  fn "$SRC/lower-level/cloud-ll.c" "$(line "$SRC/lower-level/cloud-ll.c" '^int cloud_parallax.*{$')" \
    | sed 's|^  free((void\*)cdi_);|  harness_dump_cdi(cdi_, nc_);\n  free((void*)cdi_);|'
  cat "$HERE/main.inc"
} > "$C"
grep -q harness_dump_cdi "$C" || { echo "the CDI hook did not land"; exit 1; }
gcc -O2 -std=gnu11 -fopenmp -o "$OUT/parallax_harness" "$C" -lm
echo "built $OUT/parallax_harness"
