#!/bin/bash
# Builds atmo_harness from FORCE 3.11.00's own source with the flags of FORCE's Makefile (gcc -O3 -fopenmp; no
# -ffast-math, no -march): atc-ll.c and sunview-ll.c (lower-level) are compiled AS THEY ARE, whole (allocate_atc and its
# init_* functions; sun_target_view, viewgeo, view_angle, localtime2gmt, standard_sunzenith), but for their first include
# (atc-ll.h, sunview-ll.h, which pull in the whole brick machinery: shims.h gives the minimal brick_t, meta_t, par_ll_t
# instead, with the types of atc-ll.h, meta-ll.h (the fields the files read), topo-ll.h verbatim). From atmo-ll.c (which
# has the GDAL gridding and the whole of the level 2 compilation) the functions of the sixth part are copied verbatim:
# interpolation_weights, interpolate_coarse, atmo_angledep, atmo_elevdep and apply_aoi, with the typedef iweights_t.
# The functions of the other files they call are copied verbatim too (quality-cl.c, brick_base-cl.c, utils-cl.c, topo-ll.c's
# average_elevation_cell, gas-ll.c's ozone_amount); radtran-ll.c, table-ll.c, alloc-cl.c, string-cl.c and date-cl.c are
# compiled as they are. Not FORCE's: the sun position (sun-cl.c is not opened: a table of Zeit's values), the warp of map
# coordinates to longitude and latitude (an affine map), brdf_factor (brdf-ll.c is not ported: 1 for every band).
# No GSL, no GDAL.
#
#   wsl -e bash -lc 'bash /mnt/c/.../benchmarks/vs_originals/force_atmo/make_harness.sh [FORCE_SRC] [OUT_DIR]'
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
SRC=${1:-$HOME/force-src/src/modules}
OUT=${2:-$HOME/force-ref-work/atmo}
source ~/force-ref-work/env.sh
mkdir -p "$OUT"
C=$OUT/atmo_harness.c
# a function from its first line to its closing brace in column 0
fn() { awk -v s="$2" 'NR>=s{print} NR>=s && /^}/{exit}' "$1"; }
line() { n=$(grep -n "$2" "$1" | head -1 | cut -d: -f1); [ -n "$n" ] || { echo "not found: $2 in $1" >&2; exit 1; }; echo "$n"; }
F() { fn "$SRC/$1" "$(line "$SRC/$1" "$2")"; }
ATC_H=$(sed -n '/^\/\/ viewing geometry/,/^} atc_t;/p' "$SRC/lower-level/atc-ll.h")
IW=$(sed -n '/^\/\/ interpolation weights/,/^} iweights_t;/p' "$SRC/lower-level/atmo-ll.c")
[ -n "$ATC_H" ] && [ -n "$IW" ] || { echo "types not found" >&2; exit 1; }
{
  echo "/* GENERATED by make_harness.sh: FORCE 3.11.00's atc-ll.c and sunview-ll.c (whole, but for their first include),"
  echo " * interpolation_weights, interpolate_coarse, atmo_angledep, atmo_elevdep and apply_aoi of atmo-ll.c, and functions of"
  echo " * quality-cl.c, brick_base-cl.c, utils-cl.c, topo-ll.c and gas-ll.c, verbatim, Copyright (C) 2013-2022 David Frantz,"
  echo " * GPL-3.0-or-later, plus shims.h and main.inc (Zeit). */"
  awk -v atc="$ATC_H" -v iw="$IW" '{ if ($0 == "/*@ATC_H@*/") print atc; else if ($0 == "/*@IWEIGHTS@*/") print iw; else print }' "$HERE/shims.h"
  echo
  F cross-level/quality-cl.c '^short get_qai(brick_t'
  F cross-level/quality-cl.c '^void set_qai(brick_t'
  F cross-level/quality-cl.c '^bool get_off(brick_t'
  F cross-level/quality-cl.c '^void set_off(brick_t'
  F cross-level/quality-cl.c '^void set_lowsun(brick_t'
  F cross-level/quality-cl.c '^void set_aerosol(brick_t'
  F cross-level/brick_base-cl.c '^int convert_brick_p2p'
  F cross-level/brick_base-cl.c '^void convert_brick_p2ji'
  F cross-level/brick_base-cl.c '^int find_domain'
  F cross-level/brick_base-cl.c '^bool is_brick_nodata'
  F cross-level/brick_base-cl.c '^void set_brick(brick_t'
  F cross-level/brick_base-cl.c '^float get_brick(brick_t'
  F cross-level/brick_base-cl.c '^void get_brick_range'
  F cross-level/brick_base-cl.c '^double get_brick_x'
  F cross-level/brick_base-cl.c '^double get_brick_y'
  F cross-level/brick_base-cl.c '^void get_brick_geo'
  F cross-level/brick_base-cl.c '^date_t get_brick_date'
  F cross-level/brick_base-cl.c '^int get_brick_doy'
  F cross-level/utils-cl.c '^bool fequal'
  F lower-level/topo-ll.c '^int average_elevation_cell.*{$'
  F lower-level/gas-ll.c '^float ozone_amount.*{$'
  F lower-level/atmo-ll.c '^iweights_t interpolation_weights.*{$'
  F lower-level/atmo-ll.c '^float interpolate_coarse.*{$'
  F lower-level/atmo-ll.c '^int atmo_angledep.*{$'
  F lower-level/atmo-ll.c '^int atmo_elevdep.*{$'
  F lower-level/atmo-ll.c '^int apply_aoi.*{$'
  echo
  grep -v '^#include "atc-ll.h"' "$SRC/lower-level/atc-ll.c"
  grep -v '^#include "sunview-ll.h"' "$SRC/lower-level/sunview-ll.c" | sed 's/^date_t localtime2gmt(date_t \*dmeta, double localtime, double lon);$//'
  cat "$HERE/main.inc"
} > "$C"
gcc -O3 -Wall -fopenmp -I"$SRC/lower-level" -o "$OUT/atmo_harness" "$C" \
  "$SRC/lower-level/radtran-ll.c" "$SRC/lower-level/table-ll.c" "$SRC/cross-level/alloc-cl.c" "$SRC/cross-level/string-cl.c" \
  "$SRC/cross-level/date-cl.c" -lm
echo "built $OUT/atmo_harness"
