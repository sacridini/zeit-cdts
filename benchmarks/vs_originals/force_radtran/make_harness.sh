#!/bin/bash
# Builds radtran_harness from FORCE 3.11.00's own source, with the same flags as FORCE's Makefile (gcc -O3 -fopenmp; no
# -ffast-math, no -march): radtran-ll.c and table-ll.c (lower-level), sun-cl.c and date-cl.c (cross-level) are compiled
# as they are (with string-cl.c and alloc-cl.c, which date-cl.c links to); ozone_amount (gas-ll.c, which needs GSL and the whole brick machinery for the rest of the file) and
# localtime2gmt and standard_sunzenith (sunview-ll.c, likewise) are copied verbatim into radtran_harness.c, which adds
# main.inc (the evaluation of each function on arrays read from a file). No GSL is linked.
#
#   wsl -e bash -lc 'bash /mnt/c/.../benchmarks/vs_originals/force_radtran/make_harness.sh [FORCE_SRC] [OUT_DIR]'
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
SRC=${1:-$HOME/force-src/src/modules}
OUT=${2:-$HOME/force-ref-work/radtran}
mkdir -p "$OUT"
C=$OUT/radtran_harness.c
# a function from its first line to its closing brace in column 0
fn() { awk -v s="$2" 'NR>=s{print} NR>=s && /^}/{exit}' "$1"; }
line() { grep -n "$2" "$1" | head -1 | cut -d: -f1; }
{
  echo "/* GENERATED by make_harness.sh: FORCE 3.11.00's ozone_amount (gas-ll.c), localtime2gmt and standard_sunzenith"
  echo " * (sunview-ll.c), verbatim, Copyright (C) 2013-2022 David Frantz, GPL-3.0-or-later, plus main.inc (Zeit). */"
  cat "$HERE/shims.h"
  echo
  fn "$SRC/lower-level/gas-ll.c" "$(line "$SRC/lower-level/gas-ll.c" '^float ozone_amount')"
  fn "$SRC/lower-level/sunview-ll.c" "$(line "$SRC/lower-level/sunview-ll.c" '^date_t localtime2gmt.*{$')"
  fn "$SRC/lower-level/sunview-ll.c" "$(line "$SRC/lower-level/sunview-ll.c" '^double standard_sunzenith')"
  cat "$HERE/main.inc"
} > "$C"
FLAGS="-O3 -Wall -fopenmp -I$SRC/lower-level"
gcc $FLAGS -o "$OUT/radtran_harness" "$C" "$SRC/lower-level/radtran-ll.c" "$SRC/lower-level/table-ll.c" \
  "$SRC/cross-level/sun-cl.c" "$SRC/cross-level/date-cl.c" "$SRC/cross-level/string-cl.c" "$SRC/cross-level/alloc-cl.c" -lm
echo "built $OUT/radtran_harness"
