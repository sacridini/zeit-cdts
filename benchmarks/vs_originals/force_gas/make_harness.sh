#!/bin/bash
# Builds gas_harness from FORCE 3.11.00's own source with the flags of FORCE's Makefile (gcc -O3 -fopenmp; no
# -ffast-math, no -march): gas-ll.c (lower-level) is compiled AS IT IS but for its first include (gas-ll.h, which pulls
# in the whole brick machinery: shims.h gives the minimal brick_t, atc_t, meta_t and par_ll_t instead), with
# radtran-ll.c, table-ll.c (lower-level) and alloc-cl.c, string-cl.c (cross-level) compiled as they are. The few functions
# of the cross-level files that cannot be compiled alone (quality-cl.c: get_qai, set_qai, get_off, get_shadow, get_water,
# set_vaporfill; brick_base-cl.c: convert_brick_ji2p, get_brick_nodata, utils-cl.c: fequal; dir-cl.c: fileexist;
# atc-ll.c: atc_get_band_reshaped) are copied verbatim into gas_harness.c, which adds main.inc.
#
# GSL: the real GSL 2.7 of the conda env `force-ref` (gsl_multimin_fminimizer_nmsimplex2), linked STATICALLY with its
# own reference CBLAS (libgslcblas.a): conda-forge's libgslcblas.so is a symlink to OpenBLAS, whose dnrm2 rounds
# differently from GSL's.
#
#   wsl -e bash -lc 'bash /mnt/c/.../benchmarks/vs_originals/force_gas/make_harness.sh [FORCE_SRC] [OUT_DIR]'
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
SRC=${1:-$HOME/force-src/src/modules}
OUT=${2:-$HOME/force-ref-work/gas}
source ~/force-ref-work/env.sh
GSLCBLAS_A=$CONDA_PREFIX/lib/libgslcblas.a
[ -f "$GSLCBLAS_A" ] && [ -f "$CONDA_PREFIX/lib/libgsl.a" ] || { echo "no static GSL in $CONDA_PREFIX/lib"; exit 1; }
mkdir -p "$OUT"
C=$OUT/gas_harness.c
# a function from its first line to its closing brace in column 0
fn() { awk -v s="$2" 'NR>=s{print} NR>=s && /^}/{exit}' "$1"; }
line() { n=$(grep -n "$2" "$1" | head -1 | cut -d: -f1); [ -n "$n" ] || { echo "not found: $2 in $1" >&2; exit 1; }; echo "$n"; }
F() { fn "$SRC/$1" "$(line "$SRC/$1" "$2")"; }
{
  echo "/* GENERATED by make_harness.sh: FORCE 3.11.00's gas-ll.c (but for its first include), and functions of quality-cl.c,"
  echo " * brick_base-cl.c, utils-cl.c, dir-cl.c and atc-ll.c, verbatim, Copyright (C) 2013-2022 David Frantz,"
  echo " * GPL-3.0-or-later, plus shims.h and main.inc (Zeit). */"
  cat "$HERE/shims.h"
  echo
  F cross-level/quality-cl.c '^short get_qai(brick_t'
  F cross-level/quality-cl.c '^void set_qai(brick_t'
  F cross-level/quality-cl.c '^bool get_off(brick_t'
  F cross-level/quality-cl.c '^bool get_shadow(brick_t'
  F cross-level/quality-cl.c '^bool get_water(brick_t'
  F cross-level/quality-cl.c '^void set_vaporfill(brick_t'
  F cross-level/brick_base-cl.c '^int convert_brick_ji2p'
  F cross-level/brick_base-cl.c '^int get_brick_nodata'
  F cross-level/utils-cl.c '^bool fequal'
  F cross-level/dir-cl.c '^bool fileexist'
  F lower-level/atc-ll.c '^float \*\*atc_get_band_reshaped'
  echo
  grep -v '^#include "gas-ll.h"' "$SRC/lower-level/gas-ll.c"
  cat "$HERE/main.inc"
} > "$C"
gcc -O3 -Wall -fopenmp -I"$CONDA_PREFIX/include" -I"$SRC/lower-level" -o "$OUT/gas_harness" "$C" \
  "$SRC/lower-level/radtran-ll.c" "$SRC/lower-level/table-ll.c" "$SRC/cross-level/alloc-cl.c" "$SRC/cross-level/string-cl.c" \
  -L"$CONDA_PREFIX/lib" -l:libgsl.a "$GSLCBLAS_A" -lm
echo "built $OUT/gas_harness (GSL $(gsl-config --version))"
ldd "$OUT/gas_harness" | grep -i 'gsl\|blas' || echo "no shared GSL or BLAS in the executable (static)"
