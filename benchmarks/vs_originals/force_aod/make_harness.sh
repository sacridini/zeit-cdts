#!/bin/bash
# Builds aod_harness from FORCE 3.11.00's own source with the flags of FORCE's Makefile (gcc -O3 -fopenmp; no
# -ffast-math, no -march): aod-ll.c (lower-level) is compiled AS IT IS, from its start to the end of aod_polynomial_fit
# (the rest, aod_map, interpolate_aod_map and compile_aod, is the next part of the port) but for its first include
# (aod-ll.h, which pulls in the whole brick machinery: shims.h gives the minimal brick_t, atc_t, meta_t, par_ll_t and
# top_t instead, with the types of aod-ll.h verbatim), with radtran-ll.c, table-ll.c (lower-level) and alloc-cl.c,
# string-cl.c (cross-level) compiled as they are. The few functions of the cross-level files that cannot be compiled
# alone (quality-cl.c: get_qai, get_off, get_shadow, get_cloud; brick_base-cl.c: convert_brick_ji2jip, find_domain,
# is_brick_nodata; utils-cl.c: fequal; imagefuns-cl.c: dist_transform_, connectedcomponents_ and their helpers) are
# copied verbatim into aod_harness.c, which adds main.inc.
#
# GSL: the real GSL 2.7 of the conda env `force-ref` (gsl_min_fminimizer_brent, gsl_multimin_fminimizer_nmsimplex2),
# linked STATICALLY with its own reference CBLAS (libgslcblas.a): conda-forge's libgslcblas.so is a symlink to OpenBLAS,
# whose dnrm2 rounds differently from GSL's.
#
#   wsl -e bash -lc 'bash /mnt/c/.../benchmarks/vs_originals/force_aod/make_harness.sh [FORCE_SRC] [OUT_DIR]'
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
SRC=${1:-$HOME/force-src/src/modules}
OUT=${2:-$HOME/force-ref-work/aod}
source ~/force-ref-work/env.sh
GSLCBLAS_A=$CONDA_PREFIX/lib/libgslcblas.a
[ -f "$GSLCBLAS_A" ] && [ -f "$CONDA_PREFIX/lib/libgsl.a" ] || { echo "no static GSL in $CONDA_PREFIX/lib"; exit 1; }
mkdir -p "$OUT"
C=$OUT/aod_harness.c
# a function from its first line to its closing brace in column 0
fn() { awk -v s="$2" 'NR>=s{print} NR>=s && /^}/{exit}' "$1"; }
line() { n=$(grep -n "$2" "$1" | head -1 | cut -d: -f1); [ -n "$n" ] || { echo "not found: $2 in $1" >&2; exit 1; }; echo "$n"; }
F() { fn "$SRC/$1" "$(line "$SRC/$1" "$2")"; }
{
  echo "/* GENERATED by make_harness.sh: FORCE 3.11.00's aod-ll.c (up to aod_map, and but for its first include), and"
  echo " * functions of quality-cl.c, brick_base-cl.c, utils-cl.c and imagefuns-cl.c, verbatim, Copyright (C) 2013-2022"
  echo " * David Frantz, GPL-3.0-or-later, plus shims.h and main.inc (Zeit). */"
  cat "$HERE/shims.h"
  echo
  echo "int dt_dfun(int nx, int x, int i, int y, ushort *G);"
  echo "int dt_Sep(int nx, int i, int u, int y, ushort *G);"
  echo "void ccl_tracer(int *cy, int *cx, int *dir, small *image, int *CCL, int nx, int ny);"
  echo "void ccl_contourtrace(int cy, int cx, int label, int dir, small *image, int *CCL, int nx, int ny);"
  F cross-level/quality-cl.c '^short get_qai(brick_t'
  F cross-level/quality-cl.c '^bool get_off(brick_t'
  F cross-level/quality-cl.c '^bool get_shadow(brick_t'
  F cross-level/quality-cl.c '^char get_cloud(brick_t'
  F cross-level/brick_base-cl.c '^void convert_brick_ji2jip'
  F cross-level/brick_base-cl.c '^int find_domain'
  F cross-level/utils-cl.c '^bool fequal'
  F cross-level/brick_base-cl.c '^bool is_brick_nodata'
  F cross-level/imagefuns-cl.c '^ushort \*dist_transform_'
  F cross-level/imagefuns-cl.c '^int dt_dfun'
  F cross-level/imagefuns-cl.c '^int dt_Sep'
  F cross-level/imagefuns-cl.c '^int connectedcomponents_'
  F cross-level/imagefuns-cl.c '^void ccl_tracer'
  F cross-level/imagefuns-cl.c '^void ccl_contourtrace'
  echo
  awk '/^\/\*\* This function builds the continuous AOD field/{exit} {print}' "$SRC/lower-level/aod-ll.c" | grep -v '^#include "aod-ll.h"'
  cat "$HERE/main.inc"
} > "$C"
gcc -O3 -Wall -fopenmp -I"$CONDA_PREFIX/include" -I"$SRC/lower-level" -o "$OUT/aod_harness" "$C" \
  "$SRC/lower-level/radtran-ll.c" "$SRC/lower-level/table-ll.c" "$SRC/cross-level/alloc-cl.c" "$SRC/cross-level/string-cl.c" \
  -L"$CONDA_PREFIX/lib" -l:libgsl.a "$GSLCBLAS_A" -lm
echo "built $OUT/aod_harness (GSL $(gsl-config --version))"
ldd "$OUT/aod_harness" | grep -i 'gsl\|blas' || echo "no shared GSL or BLAS in the executable (static)"
