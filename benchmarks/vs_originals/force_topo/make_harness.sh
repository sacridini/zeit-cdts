#!/bin/bash
# Builds topo_harness from FORCE 3.11.00's own source with the flags of FORCE's Makefile (gcc -O3 -fopenmp; no
# -ffast-math, no -march): topo-ll.c (lower-level) is compiled AS IT IS, whole (compile_topography, cfactor_topography,
# average_elevation_cell, and ocean, smooth, exposition, stats and illumination), but for its first include (topo-ll.h,
# which pulls in the whole brick machinery: shims.h gives the minimal brick_t, atc_t and par_ll_t instead, with top_t
# verbatim), with radtran-ll.c (illumin, f_factor, c_factor_com, c_factor_emp), table-ll.c and alloc-cl.c, string-cl.c as
# they are. The functions of the cross-level files that cannot be compiled alone (quality-cl.c, brick_base-cl.c,
# utils-cl.c, stats-cl.c, atc-ll.c's atc_get_band_reshaped) are copied verbatim into topo_harness.c, which adds main.inc.
# The warp of the DEM file by GDAL is a shim that hands over the DEM the harness holds (the same on both sides). No GSL,
# no GDAL.
#
#   wsl -e bash -lc 'bash /mnt/c/.../benchmarks/vs_originals/force_topo/make_harness.sh [FORCE_SRC] [OUT_DIR]'
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
SRC=${1:-$HOME/force-src/src/modules}
OUT=${2:-$HOME/force-ref-work/topo}
source ~/force-ref-work/env.sh
mkdir -p "$OUT"
C=$OUT/topo_harness.c
# a function from its first line to its closing brace in column 0
fn() { awk -v s="$2" 'NR>=s{print} NR>=s && /^}/{exit}' "$1"; }
line() { n=$(grep -n "$2" "$1" | head -1 | cut -d: -f1); [ -n "$n" ] || { echo "not found: $2 in $1" >&2; exit 1; }; echo "$n"; }
F() { fn "$SRC/$1" "$(line "$SRC/$1" "$2")"; }
{
  echo "/* GENERATED by make_harness.sh: FORCE 3.11.00's topo-ll.c (whole, but for its first include), and"
  echo " * functions of quality-cl.c, brick_base-cl.c, utils-cl.c, stats-cl.c and atc-ll.c, verbatim, Copyright (C) 2013-2022"
  echo " * David Frantz, GPL-3.0-or-later, plus shims.h and main.inc (Zeit). */"
  cat "$HERE/shims.h"
  echo
  F cross-level/quality-cl.c '^short get_qai(brick_t'
  F cross-level/quality-cl.c '^bool get_off(brick_t'
  F cross-level/quality-cl.c '^void set_qai(brick_t'
  F cross-level/quality-cl.c '^void set_off(brick_t'
  F cross-level/quality-cl.c '^void set_slope(brick_t'
  F cross-level/quality-cl.c '^void set_illumination(brick_t'
  F cross-level/brick_base-cl.c '^int convert_brick_p2p'
  F cross-level/brick_base-cl.c '^int convert_brick_ji2p'
  F cross-level/brick_base-cl.c '^void convert_brick_p2ji'
  F cross-level/brick_base-cl.c '^int find_domain'
  F cross-level/brick_base-cl.c '^void set_brick(brick_t'
  F cross-level/utils-cl.c '^bool fequal'
  F cross-level/stats-cl.c '^void covar_recurrence'
  F cross-level/stats-cl.c '^double variance'
  F cross-level/stats-cl.c '^double covariance'
  F cross-level/stats-cl.c '^void linreg_slope'
  F cross-level/stats-cl.c '^void linreg_intercept'
  F cross-level/stats-cl.c '^void linreg_coefs'
  F lower-level/atc-ll.c '^float \*\*atc_get_band_reshaped'
  echo
  grep -v '^#include "topo-ll.h"' "$SRC/lower-level/topo-ll.c"
  cat "$HERE/main.inc"
} > "$C"
gcc -O3 -Wall -fopenmp -I"$SRC/lower-level" -o "$OUT/topo_harness" "$C" \
  "$SRC/lower-level/radtran-ll.c" "$SRC/lower-level/table-ll.c" "$SRC/cross-level/alloc-cl.c" "$SRC/cross-level/string-cl.c" \
  -lm
echo "built $OUT/topo_harness"
