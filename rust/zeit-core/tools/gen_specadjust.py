"""Writes rust/zeit-core/src/specadjust_tables.rs from FORCE's spec-adjust-hl.c.

    python rust/zeit-core/tools/gen_specadjust.py path/to/force/src/modules/higher-level/spec-adjust-hl.c

The tables (the centres and coefficients of Scheffler, Frantz and Segl 2020, trained for
FORCE) are parsed from the C text, not retyped, and checked on the way: the shapes, the 50
`-1` of MOD02's SWIR1 centres and the 0 the C initializer leaves for the 51st, LND09 equal to
LND08, the coefficients of MOD02's SWIR1 all 0.
"""

import re
import sys

N_SEN, N_CLS, N_SRC, N_DST, N_COF = 7, 51, 6, 10, 7
SENSORS = ["LND04", "LND05", "LND07", "LND08", "LND09", "MOD01", "MOD02"]


def block(text, name):
    start = text.index(name)
    start = text.index("= {", start) + 2
    end = text.index("\n};", start)
    return text[start:end]


def groups(body):
    return [[float(v) for v in g.replace("\n", " ").split(",") if v.strip()] for g in re.findall(r"\{([^{}]*)\}", body)]


def rust_f64(v):
    s = repr(float(v))
    return s if ("." in s or "e" in s or "n" in s) else s + ".0"


def main(path, out):
    text = open(path, encoding="utf-8").read()
    center = groups(block(text, "_SPECHOMO_CENTER_"))
    coefs = groups(block(text, "_SPECHOMO_COEFS_"))
    assert len(center) == N_SEN * N_SRC, len(center)
    assert len(coefs) == N_SEN * N_DST * N_COF, len(coefs)
    short = [(i, len(g)) for i, g in enumerate(center) if len(g) != N_CLS]
    # the one row with 50 entries: MOD02 (sensor 6), SWIR1 (source band 4); the C initializer zeroes the 51st
    assert short == [(6 * N_SRC + 4, 50)], short
    row = center[6 * N_SRC + 4]
    assert row == [-1.0] * 50, "MOD02 SWIR1 centres are not fifty -1"
    row.append(0.0)
    # coefficient rows with fewer than 51 entries: the C initializer zeroes the rest
    short_c = [(i, len(g)) for i, g in enumerate(coefs) if len(g) != N_CLS]
    print("short coefficient rows (index, entries):", short_c)
    for i, n in short_c:
        assert n == 50 and all(v == 0.0 for v in coefs[i]), (i, n)
        coefs[i].append(0.0)
    assert all(v == int(v) and -32768 <= v <= 32767 for g in center for v in g)
    assert center[3 * N_SRC:4 * N_SRC] == center[4 * N_SRC:5 * N_SRC], "LND09 centres differ from LND08"
    assert coefs[3 * 70:4 * 70] == coefs[4 * 70:5 * 70], "LND09 coefficients differ from LND08"
    assert all(v == 0.0 for g in coefs[6 * 70 + 4:7 * 70:7] for v in g), "MOD02 SWIR1 coefficients are not all 0"
    lines = [
        "//! The tables of FORCE's spectral adjustment: GENERATED by tools/gen_specadjust.py from",
        "//! FORCE 3.11.00 src/modules/higher-level/spec-adjust-hl.c; do not edit by hand.",
        "//!",
        "//! Copyright (C) 2013-2022 David Frantz, FORCE, GPL-3.0-or-later (https://github.com/davidfrantz/force).",
        "//! The regressors and cluster centres are those of Scheffler, Frantz and Segl (2020), RSE 241:111723,",
        "//! doi 10.1016/j.rse.2020.111723, as trained for FORCE.",
        "//!",
        "//! `CENTER[sensor][source band][cluster]`: reflectance x 10000, the 51st cluster the global one.",
        "//! `COEFS[sensor][destination band][coefficient][cluster]`: coefficients 0..6 the weights of the",
        "//! six source bands, 6 the intercept (x 10000). Sensors: LND04, LND05, LND07, LND08, LND09, MOD01,",
        "//! MOD02; source bands BLUE GREEN RED NIR SWIR1 SWIR2; destination bands BLUE GREEN RED REDEDGE1",
        "//! REDEDGE2 REDEDGE3 BROADNIR NIR SWIR1 SWIR2.",
        "",
        "#[rustfmt::skip]",
        f"pub static CENTER: [[[i16; {N_CLS}]; {N_SRC}]; {N_SEN}] = [",
    ]
    for s in range(N_SEN):
        lines.append("    [")
        for b in range(N_SRC):
            lines.append("        [" + ", ".join(str(int(v)) for v in center[s * N_SRC + b]) + "],")
        lines.append("    ],")
    lines += ["];", "", "#[rustfmt::skip]",
              f"pub static COEFS: [[[[f64; {N_CLS}]; {N_COF}]; {N_DST}]; {N_SEN}] = ["]
    k = 0
    for s in range(N_SEN):
        lines.append("    [")
        for b in range(N_DST):
            lines.append("        [")
            for c in range(N_COF):
                lines.append("            [" + ", ".join(rust_f64(v) for v in coefs[k]) + "],")
                k += 1
            lines.append("        ],")
        lines.append("    ],")
    lines.append("];")
    lines.append("")
    # checksums for the test in specadjust.rs
    csum = sum(int(v) * (1 + i % 97) for i, v in enumerate(v for g in center for v in g))
    nsum = sum(int(v) for g in center for v in g)
    print("centre count", sum(len(g) for g in center), "sum", nsum, "weighted", csum)
    print("coefficient count", sum(len(g) for g in coefs), "sum", repr(sum(v for g in coefs for v in g)))
    open(out, "w", encoding="utf-8", newline="\n").write("\n".join(lines))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else "rust/zeit-core/src/specadjust_tables.rs")
